class QaRefusal(ValueError):
    """Refusal whose message is a fixed, non-secret reason code (safe to print; never a value)."""


def deployment_url(name):
    return f'https://{name}.convex.cloud'


def save(path, value):
    temporary = path.with_name(path.name + '.next')
    descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, 'w') as stream:
        stream.write(value)
        stream.flush()
        os.fsync(stream.fileno())
    os.replace(temporary, path)


def request_metadata(error, path, data, api):
    # Emit only fixed route templates and error codes; exception text and URLs can contain secrets.
    routes = (
        (r'/projects/[0-9]+/create_deployment', '/projects/<project>/create_deployment'),
        (r'/projects/[0-9]+/list_deployments(?:\?.*)?', '/projects/<project>/list_deployments'),
        (r'/deployments/[^/?]+/create_deploy_key', '/deployments/<deployment>/create_deploy_key'),
        (r'/deployments/[^/?]+/delete', '/deployments/<deployment>/delete'),
        (r'/deployments/[^/?]+', '/deployments/<deployment>'),
        (r'/api/update_environment_variables', '/api/update_environment_variables'),
        (r'/api/v1/list_environment_variables', '/api/v1/list_environment_variables'),
    )
    error.qa_method = 'POST' if data is not None else 'GET'
    error.qa_api = api
    error.qa_route = next((label for pattern, label in routes if re.fullmatch(pattern, path)), 'other')


def network_reason(error):
    reason = error.reason
    if isinstance(reason, socket.gaierror):
        return 'dns'
    if isinstance(reason, ssl.SSLCertVerificationError):
        return 'tls_certificate'
    if isinstance(reason, ssl.SSLError):
        return 'tls'
    if isinstance(reason, (TimeoutError, socket.timeout)):
        return 'timeout'
    if isinstance(reason, ConnectionRefusedError):
        return 'connection_refused'
    if isinstance(reason, ConnectionResetError):
        return 'connection_reset'
    return 'other_network_error'


def request(path, data=None):
    token = json.loads((Path.home() / '.convex/config.json').read_text())['accessToken']
    payload = None if data is None else json.dumps(data).encode()
    req = urllib.request.Request(API + path, data=payload, headers={
        'Authorization': 'Bearer ' + token, 'Content-Type': 'application/json'})
    try:
        with urllib.request.urlopen(req, timeout=60) as response:
            body = response.read()
            return json.loads(body) if body.strip() else None
    except urllib.error.URLError as error:
        request_metadata(error, path, data, 'management')
        raise


def render_env(original, values):
    lines = []
    seen = set()
    for line in original.splitlines():
        match = re.match(r'^(?:export\s+)?([A-Z][A-Z0-9_]*)=', line)
        key = match[1] if match else None
        if key in values or key in ('CONVEX_DEPLOY_KEY', 'STRIPE_WEBHOOK_SECRET'):
            if key in seen:
                raise ValueError('Duplicate managed environment entry')
            seen.add(key)
            continue
        lines.append(line)
    lines.extend(key + '=' + shlex.quote(value) for key, value in values.items())
    return '\n'.join(lines) + '\n'


def validate_saved(root):
    expected = json.loads((root / 'ownership.json').read_text())
    if (set(expected) != {'name', 'deploymentType', 'projectId', 'reference', 'isDefault', 'expiresAt'}
            or not re.fullmatch(r'[a-z]+-[a-z]+-[0-9]+', expected['name'])
            or expected['name'].startswith(PROD_CONVEX_PREFIXES)
            or expected['deploymentType'] != 'dev' or expected['isDefault'] is not False
            or type(expected['projectId']) is not int or expected['projectId'] <= 0
            or not re.fullmatch(r'dev/qa-fullflow-[a-f0-9]{32}', expected['reference'])
            or type(expected['expiresAt']) is not int):
        raise ValueError('Invalid owned deployment receipt')
    return expected


def env_file_values(original, names):
    # Exact shell-style values for `names`; duplicate or ambiguous entries are refused, never guessed.
    found = {}
    for line in original.splitlines():
        match = ENV_LINE.match(line)
        if not match or match[1] not in names:
            continue
        if match[1] in found:
            raise QaRefusal('ENV_DUPLICATE_ENTRY')
        try:
            tokens = shlex.split(match[2], comments=True)
        except ValueError:
            raise QaRefusal('ENV_VALUE_UNPARSEABLE') from None
        if len(tokens) != 1:
            raise QaRefusal('ENV_VALUE_UNPARSEABLE')
        found[match[1]] = tokens[0]
    return found


def production_convex_value(name, value):
    # True when ONE base-env value addresses production/shared Convex (or cannot be shown not to). The value is only
    # inspected here: never printed, returned or stored.
    if PROD_CONVEX_DEPLOYMENT in value.lower():
        return True
    if name in BASE_ENV_CONVEX_URL_NAMES:
        try:
            host = urllib.parse.urlsplit(value if '://' in value else 'https://' + value).hostname or ''
        except ValueError:
            return True  # unparseable URL: fail closed
        return host.lower().split('.')[0].startswith(PROD_CONVEX_PREFIXES)
    # CONVEX_DEPLOYMENT is `<type>:<name>` or a bare name; deploy/admin keys are `<type>:<name>|<token>`. Only the head is read.
    kind, _, deployment = value.split('|', 1)[0].partition(':')
    if not deployment:
        kind, deployment = '', kind
    return kind.strip().lower() == 'prod' or deployment.strip().lower().startswith(PROD_CONVEX_PREFIXES)


def refuse_production_base_env(original):
    # Pure: no request, no write, no output. create() runs it before intent.json and before the first management API
    # request (create_deployment), so a production base env never reaches Convex. Every occurrence is checked (a second,
    # duplicate entry cannot mask a production one). The reason is a fixed code plus variable NAMES only, never values.
    offending = set()
    for line in original.splitlines():
        match = BASE_ENV_ASSIGNMENT.match(line)
        if not match:
            continue
        name, raw = match[1], match[2]
        if PROD_CONVEX_DEPLOYMENT in raw.lower():
            offending.add(name)  # any variable, e.g. an HTTP-actions URL, naming PROD
        if name not in BASE_ENV_CONVEX_NAMES:
            continue
        try:
            values = shlex.split(raw, comments=True)
        except ValueError:
            values = [raw]
        if any(production_convex_value(name, value) for value in values):
            offending.add(name)
    if offending:
        raise QaRefusal('BASE_ENV_PRODUCTION_CONVEX names=' + ','.join(sorted(offending)))


def checked_changes(values, allowed=STRIPE_ENV_ALLOWLIST):
    # Hard-coded allowlist and per-name value guards. Pure: runs before any API call or write.
    for name in sorted(values):
        value = values[name]
        if name not in allowed:
            raise QaRefusal('ENV_NAME_NOT_ALLOWLISTED')
        if not isinstance(value, str) or not value or any(c in value for c in '\r\n\0'):
            raise QaRefusal('ENV_VALUE_INVALID')
        accept, reason = STRIPE_VALUE_GUARDS.get(name, (None, None))
        if accept and not accept(value):
            raise QaRefusal(reason)
    for derived, source in STRIPE_DERIVED.items():
        if derived in values and values[derived] != values.get(source):
            raise QaRefusal('STRIPE_DERIVED_MISMATCH')
    return [{'name': name, 'value': values[name]} for name in sorted(values)]


def with_derived(values):
    # Fill each derived name from its source (a value already present must be equal: checked_changes enforces it).
    for derived, source in STRIPE_DERIVED.items():
        if source in values:
            values.setdefault(derived, values[source])
    return values


def synth_changes(original):
    # Pure: no request, no write. Empty when the base env carries no synthetic material (behaviour unchanged).
    # Partial material is refused by name, because auth.config only adds its provider when all four are present.
    material = env_file_values(original, SYNTH_MATERIAL_NAMES)
    if not material:
        return []
    missing = [name for name in SYNTH_MATERIAL_NAMES if name not in material]
    if missing:
        raise QaRefusal('SYNTH_ENV_MISSING names=' + ','.join(missing))
    return checked_changes({**material, **SYNTH_MARKERS}, SYNTH_ALLOWLIST)


def print_derived(changes):
    names = sorted(name for name in STRIPE_DERIVED if any(c['name'] == name for c in changes))
    if names:
        print('QA_DEPLOYMENT_ENV_DERIVED names=' + ','.join(names)
              + ' from=' + ','.join(STRIPE_DERIVED[name] for name in names))


def stripe_changes(original):
    # --stripe-test-env never consumes a webhook secret from the base env file. The spec generates a fresh Stripe CLI
    # listener secret and installs it later via ownership-checked set-env; this also prevents reusing a slot's old secret.
    setup_names = (*STRIPE_TEST_REQUIRED, *STRIPE_DERIVED)
    values = env_file_values(original, setup_names)
    missing = [name for name in STRIPE_TEST_REQUIRED if name not in values]
    if missing:
        raise QaRefusal('STRIPE_TEST_ENV_MISSING names=' + ','.join(missing))
    return checked_changes(with_derived(values))


def deployment_request(url, key, path, data=None):
    # Deployment API with the deployment-scoped key; errors keep method/route only (no bodies, hosts or keys).
    payload = None if data is None else json.dumps(data).encode()
    req = urllib.request.Request(url + path, data=payload, headers={
        'Authorization': 'Convex ' + key, 'Content-Type': 'application/json'})
    try:
        with urllib.request.urlopen(req, timeout=60) as response:
            return response.read()
    except urllib.error.URLError as error:
        request_metadata(error, path, data, 'deployment')
        raise


def env_names(url, key):
    # Names only: values are dropped here and never returned, stored or printed.
    body = json.loads(deployment_request(url, key, '/api/v1/list_environment_variables') or b'null')
    variables = body.get('environmentVariables') if isinstance(body, dict) else None
    if not isinstance(variables, dict) or not all(re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', n) for n in variables):
        raise QaRefusal('ENV_READBACK_UNPARSEABLE')
    return set(variables)


def env_receipt(url, key, names):
    if not set(names) <= env_names(url, key):
        raise QaRefusal('ENV_READBACK_MISSING')
    print('QA_DEPLOYMENT_ENV_SET names=' + ','.join(sorted(names)))


def check_box_receipt(expected):
    # Box side (no management token): the controller's read-only receipt and its readonly anchors
    # (remote-qa-spec-runtime.sh) must bind exactly this deployment.
    path = os.environ.get('QA_CONVEX_OWNERSHIP_PATH', '')
    anchor = os.environ.get('QA_RECEIPT_SHA256', '')
    run_id = os.environ.get('QA_CONTROLLER_RUN_ID', '')
    if not path or not run_id or not re.fullmatch(r'[0-9a-f]{64}', anchor):
        raise QaRefusal('BOX_RECEIPT_ANCHORS_MISSING')
    raw = Path(path).read_bytes()
    if hashlib.sha256(raw).hexdigest() != anchor:
        raise QaRefusal('BOX_RECEIPT_SHA_MISMATCH')
    receipt = json.loads(raw)
    binding = receipt.pop('binding', None)
    if hashlib.sha256(json.dumps(receipt, sort_keys=True, separators=(',', ':')).encode()).hexdigest() != binding:
        raise QaRefusal('BOX_RECEIPT_BINDING_MISMATCH')
    if (receipt.get('deployment') != 'dev:' + expected['name'] or receipt.get('deploymentType') != 'dev'
            or receipt.get('controllerRunId') != run_id
            or any(receipt.get(k) != expected[k] for k in ('projectId', 'reference', 'expiresAt'))):
        raise QaRefusal('BOX_RECEIPT_MISMATCH')


def set_env(root, name, from_env):
    # Order: allowlist/value gate -> saved ownership -> key binding -> live ownership (management API on the Mac
    # controller root, the controller receipt on the box) -> authenticated read -> ONE write -> names-only read-back.
    if not re.fullmatch(r'[A-Z][A-Z0-9_]*', from_env):
        raise QaRefusal('FROM_ENV_INVALID')
    if name in STRIPE_DERIVED:
        raise QaRefusal('ENV_NAME_DERIVED_ONLY')  # set its source instead; both move together
    changes = checked_changes(with_derived({name: os.environ.get(from_env, '')}),
                              (*STRIPE_ENV_ALLOWLIST, *SET_ENV_ONLY, *EXTRA_SECRET_ALLOWLIST))
    expected = validate_saved(root)
    if expected['expiresAt'] <= int(time.time() * 1000):
        raise QaRefusal('DEPLOYMENT_EXPIRED')
    dep = expected['name']
    url = deployment_url(dep)
    controller = (root / 'dev.env').exists()
    if controller:
        key = env_file_values((root / 'dev.env').read_text(), ('CONVEX_ADMIN_KEY',)).get('CONVEX_ADMIN_KEY', '')
    else:
        key = os.environ.get('CONVEX_ADMIN_KEY', '')
    if not key.startswith('dev:' + dep + '|'):
        raise QaRefusal('DEPLOY_KEY_NOT_BOUND')
    if controller:
        actual = request('/deployments/' + dep)
        if not all(actual.get(k) == v for k, v in expected.items()) or actual.get('deploymentUrl') != url:
            raise QaRefusal('LIVE_OWNERSHIP_MISMATCH')
    else:
        check_box_receipt(expected)
    env_names(url, key)  # the scoped key must open exactly this deployment before anything is written
    print('QA_DEPLOYMENT_ENV_TARGET deployment=' + dep)
    deployment_request(url, key, '/api/update_environment_variables', {'changes': changes})
    env_receipt(url, key, [change['name'] for change in changes])
    print_derived(changes)


